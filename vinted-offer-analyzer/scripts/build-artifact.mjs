#!/usr/bin/env node
/**
 * Bundles src/ into a single React component file for Claude Artifacts
 * (artifact/VintedOfferAnalyzer.jsx) and a standalone HTML page that runs
 * the same component from CDN builds (artifact/index.html).
 *
 * The concatenation is intentionally simple: modules only use top-level
 * `export const/function` and relative imports, so stripping `import` lines
 * for local modules and the `export` keyword yields valid single-file JSX.
 */
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const read = (p) => readFileSync(join(root, p), 'utf8')

// Dependency order matters: a module must come after everything it uses at module-evaluation time.
const ORDER = [
  'src/core/math.js',
  'src/core/dates.js',
  'src/core/constants.js',
  'src/core/scoring.js',
  'src/core/scheduler.js',
  'src/core/messages.js',
  'src/core/reasoning.js',
  'src/core/analyze.js',
  'src/core/optimize.js',
  'src/core/counter.js',
  'src/core/extract.js',
  'src/theme.js',
  'src/platform/clipboard.js',
  'src/hooks/useOfferAnalysis.js',
  'src/components/icons.js',
  'src/components/ui/Card.jsx',
  'src/components/ui/Badge.jsx',
  'src/components/ui/Meter.jsx',
  'src/components/ui/Button.jsx',
  'src/components/ui/Field.jsx',
  'src/components/ui/ChipGroup.jsx',
  'src/components/OfferForm.jsx',
  'src/components/ScoreCard.jsx',
  'src/components/VerdictCard.jsx',
  'src/components/MessageCard.jsx',
  'src/components/StrategyCard.jsx',
  'src/components/OptimizeCard.jsx',
  'src/components/CounterOfferCard.jsx',
  'src/components/EmptyState.jsx',
  'src/App.jsx',
]

const reactImports = new Set()
const lucideImports = new Set()
const bodies = []
const declared = new Map() // top-level identifier → file, to catch collisions between concatenated modules
const localImports = [] // { name, file, source }: every name imported from a local module must be declared somewhere in the bundle

const IMPORT_RE = /^import\s+([\s\S]*?)\s+from\s+'([^']+)'\s*$/

for (const file of ORDER) {
  const lines = read(file).split('\n')
  const out = []
  let i = 0
  while (i < lines.length) {
    let line = lines[i]
    // Collect multi-line import statements.
    if (/^import\s/.test(line)) {
      let stmt = line
      while (!/from\s+'[^']+'\s*$/.test(stmt) && i + 1 < lines.length) {
        i++
        stmt += '\n' + lines[i]
      }
      const m = stmt.replace(/\n/g, ' ').match(IMPORT_RE)
      if (!m) throw new Error(`Unparsed import in ${file}: ${stmt}`)
      const [, clause, source] = m
      if (source === 'react') {
        clause.replace(/[{}]/g, '').split(',').map((s) => s.trim()).filter(Boolean).forEach((s) => reactImports.add(s))
      } else if (source === 'lucide-react') {
        clause.replace(/[{}]/g, '').split(',').map((s) => s.trim()).filter(Boolean).forEach((s) => lucideImports.add(s))
      } else if (!source.startsWith('.')) {
        throw new Error(`Unexpected external import '${source}' in ${file}`)
      } else {
        clause.replace(/[{}]/g, '').split(',').map((s) => s.trim().split(/\s+as\s+/)[0]).filter(Boolean).forEach((name) => localImports.push({ name, file, source }))
      }
      i++
      continue
    }
    if (/^export \* from/.test(line)) { i++; continue }
    if (/^export\b/.test(line) && !/^export (default function|async function|const|function|let|class) /.test(line)) {
      throw new Error(`Unsupported export form in ${file}: ${line}`)
    }
    line = line.replace(/^export default function /, 'function ').replace(/^export (async function|const|function|let|class) /, '$1 ')
    const decl = line.match(/^(?:async function|const|let|function|class)\s+([A-Za-z_$][\w$]*)/)
    if (decl) {
      if (declared.has(decl[1])) throw new Error(`Top-level '${decl[1]}' declared in both ${declared.get(decl[1])} and ${file}: rename it, the artifact is a single scope`)
      declared.set(decl[1], file)
    }
    out.push(line)
    i++
  }
  bodies.push(`// ───────────────────────── ${file} ─────────────────────────\n${out.join('\n').trim()}\n`)
}

// A module missing from ORDER would leave a dangling reference that only fails at runtime in the browser.
const missing = localImports.filter(({ name }) => !declared.has(name))
if (missing.length) {
  throw new Error(`Imported but not bundled (add the module to ORDER): ${missing.map((m) => `${m.name} (${m.file} ← ${m.source})`).join(', ')}`)
}

const header = `/**
 * Vinted Offer Analyzer — single-file build for Claude Artifacts.
 * Generated by scripts/build-artifact.mjs from src/. Do not edit by hand.
 * Requires: react, lucide-react, Tailwind CSS classes.
 */
import React, { ${[...reactImports].sort().join(', ')} } from 'react'
import { ${[...lucideImports].sort().join(', ')} } from 'lucide-react'
`
const jsx = `${header}\n${bodies.join('\n')}\nexport default VintedOfferAnalyzer\n`
// `--check`: run every bundling check (collisions, dangling imports) without writing the artifact.
if (process.argv.includes('--check')) {
  console.log(`bundle ok: ${ORDER.length} modules, ${declared.size} top-level names`)
  process.exit(0)
}
mkdirSync(join(root, 'artifact'), { recursive: true })
writeFileSync(join(root, 'artifact/VintedOfferAnalyzer.jsx'), jsx)

// Standalone HTML: React 18 UMD + lucide-react UMD + Babel standalone + Tailwind play CDN.
const inlineComponent = bodies.join('\n')
const html = `<title>Offerta Vinted Timing</title>
<meta name="viewport" content="width=device-width, initial-scale=1.0, viewport-fit=cover" />
<link rel="preconnect" href="https://fonts.googleapis.com" />
<link rel="stylesheet" href="https://fonts.googleapis.com/css2?family=Manrope:wght@400;500;600;700&display=swap" />
<script src="https://cdn.tailwindcss.com"></script>
<script>tailwind.config = { darkMode: 'media' }</script>
<style>
  /* Layout: one column on phones, form + results side by side from 1024px. Colours are Tailwind classes in the component. */
  :root { --bg: #f8fafc; --fg: #0f172a; }
  @media (prefers-color-scheme: dark) { :root:not([data-theme="light"]) { --bg: #020617; --fg: #f1f5f9; color-scheme: dark } }
  :root[data-theme="dark"] { --bg: #020617; --fg: #f1f5f9; color-scheme: dark }
  html, body, #root { height: 100%; margin: 0; }
  body { background: var(--bg); color: var(--fg); font-family: "Manrope", system-ui, -apple-system, "Segoe UI", sans-serif; -webkit-font-smoothing: antialiased; }
  @media (prefers-reduced-motion: reduce) { *, *::before, *::after { animation: none !important; transition: none !important; } }
</style>
<div id="root"></div>
<script src="https://cdnjs.cloudflare.com/ajax/libs/react/18.3.1/umd/react.production.min.js"></script>
<script src="https://cdnjs.cloudflare.com/ajax/libs/react-dom/18.3.1/umd/react-dom.production.min.js"></script>
<script>window.react = window.React;</script>
<script src="https://unpkg.com/lucide-react@0.577.0/dist/umd/lucide-react.min.js"></script>
<script src="https://cdnjs.cloudflare.com/ajax/libs/babel-standalone/7.26.4/babel.min.js"></script>
<script type="text/babel" data-presets="react">
const { ${[...reactImports].sort().join(', ')} } = React;
const { ${[...lucideImports].sort().join(', ')} } = LucideReact;

${inlineComponent}

ReactDOM.createRoot(document.getElementById('root')).render(<VintedOfferAnalyzer />);
</script>
`
writeFileSync(join(root, 'artifact/index.html'), html)
console.log(`artifact/VintedOfferAnalyzer.jsx (${(jsx.length / 1024).toFixed(1)} kB) and artifact/index.html (${(html.length / 1024).toFixed(1)} kB) written`)
